// Raises the site version by 0.1 (0.1, 0.2, … 0.9, 1.0, 1.1, …) and writes it to VERSION and
// src/app/version.ts. Runs from the git pre-commit hook (.githooks/pre-commit), so every commit
// gets the next version. `node scripts/bump-version.mjs --check` only prints the current one.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const file = new URL('VERSION', root);
const current = readFileSync(file, 'utf8').trim();
if (process.argv.includes('--check')) {
  console.log(current);
  process.exit(0);
}
const tenths = Math.round(Number(current) * 10) + 1; // count in tenths: no floating point drift
const next = `${Math.floor(tenths / 10)}.${tenths % 10}`;
writeFileSync(file, next + '\n');
writeFileSync(
  new URL('src/app/version.ts', root),
  `// Generated by scripts/bump-version.mjs on every commit; do not edit.\nexport const VERSION = '${next}';\n`,
);
console.log(`version ${current} -> ${next}`);
